function enforceOfficialSourceIntegrity() {
  const byUrl = new Map();
  for (const item of tenders) {
    const url = item.officialSource?.url;
    if (!url) continue;
    if (!byUrl.has(url)) byUrl.set(url, []);
    byUrl.get(url).push(item);
  }
  for (const [url, items] of byUrl) {
    const titles = new Set(items.map((item) => item.title));
    const agencies = new Set(items.map((item) => item.agency));
    if (titles.size > 1 || agencies.size > 1) {
      for (const item of items) {
        item.officialSource.verified = false;
        item.officialSource.sourceType = "官方 URL 衝突待核對";
        item.officialSource.url = "";
        item.officialSource.note = `此 URL 曾被多筆不同標案共用，已自動關閉直達，需重新抓取單案 URL。原 URL：${url}`;
      }
    }
  }
}

