function renderPackageBoard(result) {
  const taskMap = Object.fromEntries(result.tasks.map((task) => [task.name, task]));
  const packages = [
    ["資格封", ["資格文件", "領標憑據", "押標金"], "投標廠商聲明書、登記證明、納稅、公會、信用、領標憑據、押標金。"],
    ["價格封", ["價格文件"], "標價清單、總價/單價、報價單、用印與金額大小寫檢查。"],
    ["送件封裝", ["送件方式"], "截止時間、收件地點、電子投標或紙本封裝、外標封與文件順序。"],
    ["履約預備", ["施工/服務計畫", "得標後文件"], "開工、施工/服務計畫、品質職安、驗收、結算、竣工、保固。"]
  ];

  els.packageBoard.innerHTML = packages.map(([name, keys, note]) => {
    const found = keys.filter((key) => taskMap[key]?.count).length;
    const status = found === keys.length ? "完整" : found ? "需補強" : "待確認";
    return `
      <article class="package-card ${status === "完整" ? "complete" : ""}">
        <div>
          <strong>${name}</strong>
          <span>${status}</span>
        </div>
        <p>${note}</p>
        <small>${keys.map((key) => `${key}:${taskMap[key]?.count ? "有" : "待核"}`).join(" / ")}</small>
      </article>
    `;
  }).join("");
}

