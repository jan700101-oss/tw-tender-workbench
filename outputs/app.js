function parseOfficialTenderText(text, url) {
  const normalized = text.replace(/\r/g, "\n").replace(/[ \t]+/g, " ").trim();
  const lines = normalized.split(/\n+/).map((line) => line.trim()).filter(Boolean);
  const joined = lines.join("\n");
  const pick = (patterns) => {
    for (const pattern of patterns) {
      const match = joined.match(pattern);
      if (match?.[1]) return match[1].trim();
    }
    return "";
  };
  const agency = pick([/機關名稱[：:\s]+([^\n]+)/, /招標機關[：:\s]+([^\n]+)/, /機關[：:\s]+([^\n]+)/]);
  const caseNo = pick([/標案案號[：:\s]+([^\n]+)/, /案號[：:\s]+([^\n]+)/]);
  const title = pick([/標案名稱[：:\s]+([^\n]+)/, /採購案名稱[：:\s]+([^\n]+)/, /案名[：:\s]+([^\n]+)/]);
  const budgetText = pick([/預算金額[：:\s]+([0-9,]+)\s*元?/, /預算[：:\s]+([0-9,]+)\s*元?/]);
  const deadlineRaw = pick([/截止投標[：:\s]+([^\n]+)/, /投標截止[：:\s]+([^\n]+)/, /截止收件[：:\s]+([^\n]+)/]);
  const pk = (url.match(/(?:pkPmsMain=|pk=)([^&#]+)/) || [])[1] || "";
  const budget = budgetText ? Math.max(1, Math.round(Number(budgetText.replace(/,/g, "")) / 10000)) : 0;
  const rocDate = deadlineRaw.match(/(\d{3})[\/.-](\d{1,2})[\/.-](\d{1,2})/);
  const westernDate = deadlineRaw.match(/(20\d{2})[\/.-](\d{1,2})[\/.-](\d{1,2})/);
  let deadline = "2026-06-30";
  if (rocDate) deadline = `${Number(rocDate[1]) + 1911}-${String(rocDate[2]).padStart(2, "0")}-${String(rocDate[3]).padStart(2, "0")}`;
  if (westernDate) deadline = `${westernDate[1]}-${String(westernDate[2]).padStart(2, "0")}-${String(westernDate[3]).padStart(2, "0")}`;
  const category = /室內裝修|裝修|天花|隔間|地坪|油漆|木作|系統櫃/.test(joined + title) ? "室內裝修" : /管線|污水|排水/.test(joined + title) ? "管線工程" : "工程類";
  const region = (agency.match(/^(台北市|臺北市|新北市|桃園市|台中市|臺中市|台南市|臺南市|高雄市|基隆市|新竹縣|苗栗縣|彰化縣|雲林縣|嘉義縣|屏東縣|宜蘭縣|花蓮縣)/) || [])[1]?.replace("臺", "台") || "未分類";
  const validUrl = /^https:\/\/(planpe|web)\.pcc\.gov\.tw\//.test(url) && pk;
  const missing = [];
  if (hasEncodingDamage(normalized)) missing.push("文字編碼異常");
  if (!validUrl) missing.push("政府單案 URL");
  if (!agency) missing.push("機關");
  if (!title) missing.push("標案名稱");
  if (!caseNo) missing.push("案號");
  return { agency, caseNo, title, budget, deadline, category, region, pk, missing, raw: normalized };
}

