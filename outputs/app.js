function renderPagination(totalPages, totalResults) {
  if (!totalResults || totalPages <= 1) {
    els.pagination.innerHTML = "";
    return;
  }
  const pageButtons = [];
  for (let page = 1; page <= totalPages; page += 1) {
    pageButtons.push(`<button type="button" data-page="${page}" class="${page === state.page ? "active" : ""}" aria-current="${page === state.page ? "page" : "false"}">${page}</button>`);
  }
  els.pagination.innerHTML = `
    <button type="button" data-page="${state.page - 1}" ${state.page === 1 ? "disabled" : ""} aria-label="上一頁">上一頁</button>
    ${pageButtons.join("")}
    <button type="button" data-page="${state.page + 1}" ${state.page === totalPages ? "disabled" : ""} aria-label="下一頁">下一頁</button>
  `;
}

