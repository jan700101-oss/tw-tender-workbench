function getFiltered() {
  const query = els.query.value.trim().toLowerCase();
  const agencyQuery = els.agencyQuery.value.trim().toLowerCase();
  const region = els.region.value;
  const category = els.category.value;
  const budget = els.budget.value;
  const status = els.status.value;
  const period = els.period.value;
  const sourceStatus = els.sourceStatus.value;

  let results = tenders.filter((item) => {
    if (Number.isFinite(item.budget) && item.budget > 10000) return false;
    const queryMatch = !query || [item.title, item.agency, item.region, item.category, ...item.tags].join(" ").toLowerCase().includes(query);
    const agencyMatch = !agencyQuery || item.agency.toLowerCase().includes(agencyQuery);
    const regionMatch = region === "all" || item.region === region;
    const categoryMatch = category === "all" || item.category === category;
    const remaining = daysLeft(item.deadline);
    const statusMatch = status === "all" || (status === "尚未截止" ? remaining !== null && remaining >= 0 : timeStatus(item) === status);
    const sourceMatch = sourceStatus === "all" || (sourceStatus === "verified" && item.officialSource?.verified) || (sourceStatus === "pending" && !item.officialSource?.verified);
    let periodMatch = true;
    if (period !== "all") {
      const published = /^20\d{2}-\d{2}-\d{2}$/.test(item.publishDate) ? new Date(`${item.publishDate}T00:00:00+08:00`) : null;
      const deadline = /^20\d{2}-\d{2}-\d{2}$/.test(item.deadline) ? new Date(`${item.deadline}T00:00:00+08:00`) : null;
      const referenceDate = published || deadline;
      const cutoff = new Date(`${taipeiTodayText()}T00:00:00+08:00`);
      cutoff.setDate(cutoff.getDate() - Number(period));
      periodMatch = referenceDate ? referenceDate >= cutoff : true;
    }
    let budgetMatch = true;
    if (budget !== "all") {
      if (budget === "known") {
        budgetMatch = Number.isFinite(item.budget);
      } else {
        const [min, max] = budget.split("-").map(Number);
        budgetMatch = Number.isFinite(item.budget) && item.budget >= min && item.budget <= max;
      }
    }
    return queryMatch && agencyMatch && regionMatch && categoryMatch && statusMatch && sourceMatch && periodMatch && budgetMatch;
  });

  results = results.sort((a, b) => {
    if (state.sort === "fit") return (b.fit ?? -1) - (a.fit ?? -1);
    if (state.sort === "budget") return (b.budget ?? -1) - (a.budget ?? -1);
    const aDate = daysLeft(a.deadline);
    const bDate = daysLeft(b.deadline);
    if (aDate === null && bDate === null) return new Date(b.publishDate) - new Date(a.publishDate);
    if (aDate === null) return 1;
    if (bDate === null) return -1;
    return aDate - bDate;
  });

  return results;
}

function renderMetrics(results) {
  const openItems = results.filter((item) => daysLeft(item.deadline) !== null && daysLeft(item.deadline) >= 0);
  const totalBudget = results.reduce((sum, item) => sum + (Number.isFinite(item.budget) ? item.budget : 0), 0);
  els.metricMatches.textContent = results.length;
  els.metricAverage.textContent = openItems.length;
  els.metricFit.textContent = results.filter((item) => item.officialSource?.verified).length;
  els.metricSiteVisit.textContent = money(totalBudget);
  const periodLabels = { "7": "近 7 天", "30": "近 30 天", "90": "近 3 個月", "180": "近 6 個月", all: "不限期間" };
  els.resultHeadline.textContent = `${periodLabels[els.period.value]}找到 ${results.length} 筆標案`;

  const categoryCounts = results.reduce((counts, item) => {
    counts[item.category] = (counts[item.category] || 0) + 1;
    return counts;
  }, {});
  els.categorySummary.innerHTML = Object.entries(categoryCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([category, count]) => `<button type="button" data-result-category="${category}"><strong>${category}</strong><span>${count} 件</span></button>`)
    .join("") || `<span class="empty-summary">目前條件沒有分類結果</span>`;

  document.querySelectorAll("[data-metric-filter]").forEach((button) => {
    const filter = button.dataset.metricFilter;
    const active = (filter === "all" && els.status.value === "all" && els.sourceStatus.value === "all" && els.budget.value === "all")
      || (filter === "open" && els.status.value === "尚未截止")
      || (filter === "verified" && els.sourceStatus.value === "verified")
      || (filter === "known-budget" && els.budget.value === "known");
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
}

